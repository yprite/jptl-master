from __future__ import annotations

from typing import Any


def _question(
    *,
    passage: str,
    question: str,
    choices: list[str],
    correct_answer: str,
    explanation: str,
    difficulty: int,
) -> dict[str, Any]:
    return {
        "passage": passage,
        "question": question,
        "choices": choices,
        "correct_answer": correct_answer,
        "explanation": explanation,
        "difficulty": difficulty,
    }


def _n5_commute_question(
    *,
    name: str,
    wake_time: str,
    transport: str,
    destination: str,
    after_activity: str,
) -> dict[str, Any]:
    transport_choices = ["バス", "電車", "自転車", "歩いて"]
    answer = f"{transport}で行きます"
    choices = [
        f"{choice}で行きます" if choice != "歩いて" else "歩いて行きます"
        for choice in transport_choices
    ]
    passage = (
        f"{name}さんは毎朝{wake_time}に起きます。朝ごはんを食べてから、"
        f"{transport}で{destination}へ行きます。{destination}のあとで、{after_activity}をしてから家に帰ります。"
    )
    return _question(
        passage=passage,
        question=f"{name}さんは{destination}へどうやって行きますか。",
        choices=choices,
        correct_answer=answer,
        explanation=f"지문에 `{transport}で{destination}へ行きます`라고 나와 있습니다.",
        difficulty=1,
    )


def _n5_plan_question(
    *,
    who: str,
    location: str,
    sunny_plan: str,
    rainy_plan: str,
) -> dict[str, Any]:
    passage = (
        f"今度の日曜日に{who}と{location}へ行く予定です。"
        f"天気がよければ{sunny_plan}。でも、雨が降ったら{rainy_plan}ことにしました。"
    )
    choices = [
        sunny_plan.rstrip("。"),
        rainy_plan.rstrip("。"),
        "家で寝ます",
        "仕事をします",
    ]
    return _question(
        passage=passage,
        question="雨が降ったら、どうしますか。",
        choices=choices,
        correct_answer=rainy_plan.rstrip("。"),
        explanation=f"비가 오면 `{rainy_plan}` 계획입니다.",
        difficulty=1,
    )


def _n5_notice_question(
    *,
    title: str,
    body: str,
    question: str,
    choices: list[str],
    correct_answer: str,
    explanation: str,
) -> dict[str, Any]:
    return _question(
        passage=f"【{title}】\n{body}",
        question=question,
        choices=choices,
        correct_answer=correct_answer,
        explanation=explanation,
        difficulty=1,
    )


